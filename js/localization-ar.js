  function dynamicTranslation(value) {
    let match = value.match(/^(\d+) Traveller(?:s)? · (.+)$/);
    if (match) return match[1] + " " + (Number(match[1]) === 1 ? "مسافر" : "مسافرين") + " · " + (AR[match[2]] || match[2]);
    match = value.match(/^Hi,\s*(.+)$/);
    if (match) return "مرحبًا، " + match[1];
    match = value.match(/^([A-Z]{3}\s*→\s*[A-Z]{3}\s*·\s*)(.+)$/);
    if (match && LOCATIONS[match[2]]) return match[1] + LOCATIONS[match[2]];
    match = value.match(/^(Dubai|Sharjah) to (.+) flights$/);
    if (match && CITIES[match[1]] && CITIES[match[2]]) return "رحلات من " + CITIES[match[1]] + " إلى " + CITIES[match[2]];
    match = value.match(/^(Dubai|Sharjah)\s*→\s*(.+)$/);
    if (match && CITIES[match[1]] && CITIES[match[2]]) return CITIES[match[1]] + " ← " + CITIES[match[2]];
    match = value.match(/^©\s+(\d{4})\s+Kridiya Travel and Tourism FZ-LLC\. All rights reserved\.$/);
    if (match) return "© " + match[1] + " كريديا للسفر والسياحة ذ.م.م. جميع الحقوق محفوظة.";
    if (/^(Mon|Tue|Wed|Thu|Fri|Sat|Sun),?\s/.test(value)) {
      return value
        .replace(/^Mon,?/, "الاثنين").replace(/^Tue,?/, "الثلاثاء").replace(/^Wed,?/, "الأربعاء")
        .replace(/^Thu,?/, "الخميس").replace(/^Fri,?/, "الجمعة").replace(/^Sat,?/, "السبت").replace(/^Sun,?/, "الأحد")
        .replace(/\b(Jan|Feb|Mar|Apr|May|Jun|Jul|Aug|Sep|Oct|Nov|Dec)\b/g, function (month) { return MONTHS[month]; });
    }
    return "";
  }

  function translateValue(value) {
    const trimmed = value.trim();
    if (!trimmed) return value;
    const translated = AR[trimmed] || dynamicTranslation(trimmed);
    if (!translated) return value;
    return value.replace(trimmed, translated);
  }

  function contextualTranslation(element, value) {
    const trimmed = value.trim();
    if (element && element.matches("#fl-class option")) {
      if (trimmed === "Business") return value.replace(trimmed, "درجة رجال الأعمال");
      if (trimmed === "First") return value.replace(trimmed, "الدرجة الأولى");
    }
    return translateValue(value);
  }

  function translateElement(element) {
    if (!(element instanceof Element) || element.closest(SKIP)) return;
    ATTRIBUTES.forEach(function (name) {
      if (!element.hasAttribute(name)) return;
      const current = element.getAttribute(name);
      const next = translateValue(current);
      if (next !== current) element.setAttribute(name, next);
    });
    if (element instanceof HTMLInputElement && ["button", "submit", "reset"].includes(element.type) && element.value) {
      const next = translateValue(element.value);
      if (next !== element.value) element.value = next;
    }
  }

  function translateTree(root) {
    if (!root || document.querySelector("main.legal-page")) return;
    if (root.nodeType === Node.TEXT_NODE) {
      if (root.parentElement && !root.parentElement.closest(SKIP)) {
        const next = contextualTranslation(root.parentElement, root.nodeValue);
        if (next !== root.nodeValue) root.nodeValue = next;
      }
      return;
    }
    if (root.nodeType !== Node.ELEMENT_NODE && root.nodeType !== Node.DOCUMENT_FRAGMENT_NODE && root.nodeType !== Node.DOCUMENT_NODE) return;
    if (root.nodeType === Node.ELEMENT_NODE) translateElement(root);
    const walker = document.createTreeWalker(root, NodeFilter.SHOW_ELEMENT | NodeFilter.SHOW_TEXT);
    let node;
    while ((node = walker.nextNode())) {
      if (node.nodeType === Node.TEXT_NODE) {
        if (node.parentElement && !node.parentElement.closest(SKIP)) {
          const next = contextualTranslation(node.parentElement, node.nodeValue);
          if (next !== node.nodeValue) node.nodeValue = next;
        }
      } else translateElement(node);
    }
  }

  function start() {
    if (document.querySelector("main.legal-page")) return;
    document.body.classList.add("is-arabic");
    translateTree(document.body);
    const observer = new MutationObserver(function (records) {
      records.forEach(function (record) {
        record.addedNodes.forEach(translateTree);
        if (record.type === "characterData") translateTree(record.target);
      });
    });
    observer.observe(document.body, { childList: true, subtree: true, characterData: true });
  }

  if (document.readyState === "loading") document.addEventListener("DOMContentLoaded", start, { once: true });
  else start();
