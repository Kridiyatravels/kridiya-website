  window.KRIDIYA_AR_TRANSLATIONS = AR;
  const SKIP = "script,style,noscript,code,pre,[translate='no'],[data-no-localize],.legal-arabic";
  const ATTRIBUTES = ["placeholder", "aria-label", "title", "data-label", "alt"];
  const MONTHS = { Jan: "يناير", Feb: "فبراير", Mar: "مارس", Apr: "أبريل", May: "مايو", Jun: "يونيو", Jul: "يوليو", Aug: "أغسطس", Sep: "سبتمبر", Oct: "أكتوبر", Nov: "نوفمبر", Dec: "ديسمبر" };
